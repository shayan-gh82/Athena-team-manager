export function translate(source: string, language: Language): string {
  if (language === 'en') return source
  return fa[source] ?? source
}

export function useI18n() {
  const dispatch = useAppDispatch()
  const language = useAppSelector((s) => s.ui.language ?? 'en')
  const t = useCallback((source: string) => translate(source, language), [language])
  const setLocale = useCallback((next: Language) => dispatch(setLanguage(next)), [dispatch])
  const toggleLanguage = useCallback(() => dispatch(setLanguage(language === 'en' ? 'fa' : 'en')), [dispatch, language])
  const locale = language === 'fa' ? 'fa-IR' : 'en-US'
  const dir = language === 'fa' ? 'rtl' : 'ltr'
  return { language, t, setLocale, toggleLanguage, locale, dir }
}

export function localizeEnum(value: string, language: Language) {
  return translate(value, language)
}

export function formatLocalizedDate(
  value: string | undefined,
  language: Language,
  options?: Intl.DateTimeFormatOptions,
) {
  if (!value) return '—'
  const date = new Date(value.includes('T') ? value : `${value}T00:00:00`)
  if (Number.isNaN(date.getTime())) return value
  return new Intl.DateTimeFormat(
    language === 'fa' ? 'fa-IR' : 'en-US',
    options ?? { month: 'short', day: 'numeric', year: 'numeric' },
  ).format(date)
}
